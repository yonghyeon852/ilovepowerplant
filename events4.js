  // 효과 묶음을 글 조각으로 (선택지 설명과 결과 문장에 같이 씀)
  function parts(s, fx) {
    const p = [];
    if (fx.m) p.push((fx.m > 0 ? '+' : '−') + won(cash(s, Math.abs(fx.m))));
    if (fx.h) p.push('민심 ' + (fx.h > 0 ? '+' : '−') + Math.abs(fx.h));
    if (fx.dem) p.push(fx.dem[1] + '개월 수요 ' + pct(fx.dem[0]));
    if (fx.der) p.push(fx.der[2] + '개월 ' + KIND_NAME[fx.der[0]] + ' 출력 −' + Math.round(fx.der[1] * 100) + '%');
    if (fx.exp) p.push(fx.exp[1] + '개월 수출 단가 ' + pct(fx.exp[0]));
    if (fx.tech) p.push('다음 연구 확률 +' + Math.round(fx.tech * 100) + '%');
    return p;
  }
  function run(s, fx, name) {
    if (fx.m) s.money += (fx.m > 0 ? 1 : -1) * cash(s, Math.abs(fx.m));
    if (fx.h) s.happiness = clamp(s.happiness + fx.h, 0, 100);
    if (fx.dem) addEffect(s, { name: name + ' (수요 ' + pct(fx.dem[0]) + ')', demandMult: fx.dem[0] }, fx.dem[1]);
    if (fx.der) addEffect(s, { name: name + ' (' + KIND_NAME[fx.der[0]] + ' 출력 −' + Math.round(fx.der[1] * 100) + '%)', kindDerate: { kind: fx.der[0], factor: fx.der[1] } }, fx.der[2]);
    if (fx.exp) addEffect(s, { name: name + ' (수출 단가 ' + pct(fx.exp[0]) + ')', exportMult: fx.exp[0] }, fx.exp[1]);
    if (fx.tech) s.techBoost = (s.techBoost || 0) + fx.tech;
  }
  const tail = (ps) => (ps.length ? ' (' + ps.join(' · ') + ')' : '');

