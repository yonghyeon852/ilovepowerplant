//      · 연구에 보탠다 (−100억 · 다음 연구 확률 +5%)    ↔  민심을 얻는다
//      · 운에 맡긴다 (60% 민심 +1 / 아니면 −1)        ↔  조용히 넘긴다 (효과 없음)
//    웃음은 상황 설명과 결과 한마디에 두고, 선택지 자체는 대통령이 실제로 할 법한 대응으로 쓴다
//  - 효과 크기: 민심 ±1~2, 돈 100억 단위(경제 규모에 따라 커짐), 한두 달짜리 수요 ±1~2%, 다음 연구 확률 +5%
//    봇 측정(2026-11-21, 노선 셋 × 8판, 선택지를 다시 짜기 전): 민심 얻는 선택만 고르면 무난한 선택만 고를 때보다 약 +20점
//  - 인물·작품 이름은 전부 지어낸 것 (실제 인물·단체와 무관한 패러디)
//
//  카드 쓰는 법: F(이름표, 그림 글자, 제목, 설명, [선택지…], 조건)
//    선택지 = [버튼 글, 효과, 결과 한마디]   (운에 맡기는 선택은 결과 한마디가 [잘됐을 때, 안됐을 때])
