//  - 7번 묶음은 실제로 있었던 에너지 정책 사건을 조금 비튼 것 (나라 · 이름 · 숫자를 바꿈)
//  - 효과 크기: 민심(여론) ±1~6, 돈 100억 단위(경제 규모에 따라 커짐), 몇 달짜리 출력·수요·요금 변화, 연구소 규모, 탄소세
//  - 정당 · 단체 · 인물은 전부 지어낸 것 (실제와 무관)
//
//  카드 쓰는 법: F(이름표, 그림 글자, 제목, 설명, [선택지…], 조건)
//    선택지 = [버튼 글, 효과, 결과 한마디]   (운에 맡기는 선택은 결과 한마디가 [잘됐을 때, 안됐을 때])
//    효과 = { h: 민심, m: 돈(100억 단위, 음수면 비용), tech: 다음 연구 확률, lab: 연구소 규모 변화,
//             dem: [수요 배율, 개월], der: [설비 종류('thermal' = 화력 전부), 줄어드는 비율, 개월], stop: [설비 묶음, 개월] (1기 정지),
//             delay: [설비 묶음, 개월] (건설 중인 설비 공사 지연), gas / coalf: [연료비 배율, 개월], cap: [전기값 상한 배율, 개월],
//             clean: [무탄소 설비 건설비 배율, 개월], exp: [수출 단가 배율, 개월], ctax: 탄소세 인상 비율, pop: 인구(수요) 변화 비율,
//             coin: 성공 확률 + win / lose 효과 }
//    조건 = { months: [나오는 달], seasons: [계절], minYear: 몇 년 차부터, cond: (state) => 참/거짓 }
