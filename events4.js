//      · 돈을 쓰고 민심을 얻는다 (−100억 · 민심 +2)  ↔  아낀다 (효과 없음)
//      · 돈을 번다 (+100억, 때로 민심 −1)            ↔  민심을 얻는다 (민심 +1)
